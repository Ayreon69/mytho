function slug(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 48);
}

const build = (rows: Raw[], spicy: boolean): Question[] => rows.map(([text, hint]) => ({ id: slug(text), text, hint, ...(spicy ? { spicy: true } : {}) }));

